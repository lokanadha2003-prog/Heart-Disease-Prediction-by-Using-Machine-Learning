# ============================================================
# LOAD MODEL AND SCALER
# ============================================================

@st.cache_resource  # Cache so the model is only loaded once
def load_artifacts():
    """
    Load the pre-trained XGBoost model, StandardScaler, and
    feature name list from disk.

    These files are generated by running heart_disease_dissertation.py.
    """
    model   = joblib.load('best_model.pkl')
    scaler  = joblib.load('scaler.pkl')
    features = joblib.load('feature_names.pkl')
    return model, scaler, features

# Check if model files exist
if not os.path.exists('best_model.pkl'):
    st.error("""
    ⚠️ **Model files not found!**

    Please run `heart_disease_dissertation.py` first to train and save:
    - `best_model.pkl`
    - `scaler.pkl`
    - `feature_names.pkl`

    Then restart this Streamlit app.
    """)
    st.stop()

model, scaler, feature_names = load_artifacts()

# ============================================================
# HEADER SECTION
# ============================================================

st.markdown('<div class="main-title">❤️ Heart Disease Predictor</div>', unsafe_allow_html=True)
st.markdown('<div class="sub-title">MSc Dissertation Project — Cardiovascular Risk Assessment using Machine Learning</div>',
            unsafe_allow_html=True)

st.markdown("---")

# ============================================================
# ABOUT SECTION (Collapsible)
# ============================================================

with st.expander("ℹ️ About this Application"):
    st.markdown("""
    This application uses a machine learning model trained on the **Cardiovascular Disease Dataset**
    (70,000 patient records). The model was built as part of an MSc dissertation project and
    compares **5 algorithms**: Logistic Regression, Decision Tree, Random Forest, SVM, and XGBoost.

    **Best model deployed**: XGBoost (highest ROC-AUC after GridSearchCV tuning)

    **Input**: Patient clinical and lifestyle data  
    **Output**: Probability of cardiovascular disease + binary prediction

    > ⚠️ *This tool is for educational/research purposes only and is NOT a substitute for professional medical advice.*
    """)

# ============================================================
# INPUT FORM
# ============================================================

st.markdown('<div class="section-header">👤 Patient Information</div>', unsafe_allow_html=True)

col1, col2 = st.columns(2)

with col1:
    age = st.number_input(
        "Age (years)",
        min_value=1, max_value=100, value=45, step=1,
        help="Patient's age in years"
    )
    gender = st.selectbox(
        "Gender",
        options=[(1, "Female"), (2, "Male")],
        format_func=lambda x: x[1],
        help="1 = Female, 2 = Male (as encoded in the dataset)"
    )
    height = st.number_input(
        "Height (cm)",
        min_value=100, max_value=250, value=170, step=1
    )
    weight = st.number_input(
        "Weight (kg)",
        min_value=30.0, max_value=200.0, value=70.0, step=0.5
    )

with col2:
    ap_hi = st.number_input(
        "Systolic Blood Pressure (mmHg)",
        min_value=50, max_value=250, value=120, step=1,
        help="Top number in a blood pressure reading. Normal: <120"
    )
    ap_lo = st.number_input(
        "Diastolic Blood Pressure (mmHg)",
        min_value=30, max_value=150, value=80, step=1,
        help="Bottom number in a blood pressure reading. Normal: <80"
    )
    cholesterol = st.selectbox(
        "Cholesterol Level",
        options=[(1, "Normal"), (2, "Above Normal"), (3, "Well Above Normal")],
        format_func=lambda x: x[1]
    )
    gluc = st.selectbox(
        "Glucose Level",
        options=[(1, "Normal"), (2, "Above Normal"), (3, "Well Above Normal")],
        format_func=lambda x: x[1]
    )

st.markdown('<div class="section-header">🏃 Lifestyle Factors</div>', unsafe_allow_html=True)

col3, col4, col5 = st.columns(3)

with col3:
    smoke = st.radio("Smoking", options=[(0, "No"), (1, "Yes")],
                     format_func=lambda x: x[1], horizontal=True)
with col4:
    alco = st.radio("Alcohol Intake", options=[(0, "No"), (1, "Yes")],
                    format_func=lambda x: x[1], horizontal=True)
with col5:
    active = st.radio("Physically Active", options=[(1, "Yes"), (0, "No")],
                      format_func=lambda x: x[1], horizontal=True)

# ============================================================
# PREDICTION LOGIC
# ============================================================

st.markdown("---")

if st.button("🔍 Predict Heart Disease Risk", use_container_width=True):

    # Validate blood pressure
    if ap_hi < ap_lo:
        st.error("⚠️ Systolic BP must be greater than Diastolic BP. Please check your inputs.")
        st.stop()

    # Compute BMI (matching the feature engineering step from training)
    bmi = weight / ((height / 100) ** 2)

    # Build input row in the exact same column order as training
    # feature_names order: age, gender, height, weight, ap_hi, ap_lo, cholesterol, gluc, smoke, alco, active, bmi
    gender_val      = gender[0]
    cholesterol_val = cholesterol[0]
    gluc_val        = gluc[0]
    smoke_val       = smoke[0]
    alco_val        = alco[0]
    active_val      = active[0]

    # Create a DataFrame with correct column names (must match training)
    input_dict = {
        'age':         [age],
        'gender':      [gender_val],
        'height':      [height],
        'weight':      [weight],
        'ap_hi':       [ap_hi],
        'ap_lo':       [ap_lo],
        'cholesterol': [cholesterol_val],
        'gluc':        [gluc_val],
        'smoke':       [smoke_val],
        'alco':        [alco_val],
        'active':      [active_val],
        'bmi':         [round(bmi, 2)]
    }

    input_df = pd.DataFrame(input_dict)

    # Reorder to match exact training feature order
    input_df = input_df[feature_names]

    # Scale using the saved StandardScaler
    input_scaled = scaler.transform(input_df)

    # Get prediction and probability
    prediction   = model.predict(input_scaled)[0]          # 0 or 1
    probability  = model.predict_proba(input_scaled)[0][1] # Prob of class 1

    # ---- DISPLAY RESULTS ----

    if prediction == 1:
        st.markdown(f"""
        <div class="pred-card pred-positive">
            ⚠️ HIGH RISK — Heart Disease Detected<br>
            <span style="font-size:1.1rem; font-weight:400">
            The model predicts a <strong>{probability*100:.1f}%</strong> probability of cardiovascular disease.
            </span>
        </div>
        """, unsafe_allow_html=True)
    else:
        st.markdown(f"""
        <div class="pred-card pred-negative">
            ✅ LOW RISK — No Heart Disease Detected<br>
            <span style="font-size:1.1rem; font-weight:400">
            The model predicts a <strong>{(1-probability)*100:.1f}%</strong> probability of no cardiovascular disease.
            </span>
        </div>
        """, unsafe_allow_html=True)

    st.markdown("---")

    # Probability gauges
    st.markdown("### 📊 Risk Probability Breakdown")
    col_a, col_b = st.columns(2)
    with col_a:
        st.metric("❤️ Disease Probability", f"{probability*100:.1f}%")
        st.progress(float(probability))
    with col_b:
        st.metric("💚 Healthy Probability", f"{(1-probability)*100:.1f}%")
        st.progress(float(1 - probability))

    # Input summary table
    st.markdown("### 📋 Your Input Summary")
    summary = pd.DataFrame({
        'Feature': ['Age', 'Gender', 'Height', 'Weight', 'Systolic BP',
                    'Diastolic BP', 'Cholesterol', 'Glucose',
                    'Smoking', 'Alcohol', 'Physical Activity', 'BMI'],
        'Value': [
            f"{age} years",
            "Female" if gender_val == 1 else "Male",
            f"{height} cm",
            f"{weight} kg",
            f"{ap_hi} mmHg",
            f"{ap_lo} mmHg",
            {1: "Normal", 2: "Above Normal", 3: "Well Above Normal"}[cholesterol_val],
            {1: "Normal", 2: "Above Normal", 3: "Well Above Normal"}[gluc_val],
            "Yes" if smoke_val else "No",
            "Yes" if alco_val else "No",
            "Yes" if active_val else "No",
            f"{bmi:.1f} kg/m²"
        ]
    })
    st.dataframe(summary, use_container_width=True, hide_index=True)

    # Clinical interpretation
    st.markdown("### 🩺 Clinical Risk Factors Identified")
    risks = []
    if age >= 50:     risks.append("• Age ≥ 50 years — increased cardiovascular risk")
    if ap_hi >= 140:  risks.append("• Systolic BP ≥ 140 mmHg — Stage 2 Hypertension")
    elif ap_hi >= 130: risks.append("• Systolic BP ≥ 130 mmHg — Stage 1 Hypertension")
    if cholesterol_val >= 2: risks.append("• Elevated cholesterol level")
    if gluc_val >= 2:  risks.append("• Elevated glucose level (possible pre-diabetes/diabetes)")
    if bmi >= 30:      risks.append(f"• BMI {bmi:.1f} kg/m² — Obese (Class I+)")
    elif bmi >= 25:    risks.append(f"• BMI {bmi:.1f} kg/m² — Overweight")
    if smoke_val:      risks.append("• Smoking — significant independent risk factor")
    if alco_val:       risks.append("• Alcohol consumption")
    if not active_val: risks.append("• Physical inactivity — increases cardiovascular risk")

    if risks:
        for r in risks:
            st.warning(r)
    else:
        st.success("✅ No major clinical risk factors identified from your inputs.")

    st.info("""
    > ⚠️ **Disclaimer**: This prediction is generated by a machine learning model
    trained on population-level data. It is intended for **educational and research purposes only**.
    Please consult a qualified healthcare professional for medical advice.
    """)

